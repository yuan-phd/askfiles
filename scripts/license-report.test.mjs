import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { isAllowed, licenseOf, walkDependencies } from './license-report.mjs';

let root;
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'askfiles-licenses-'));
});
afterEach(() => rmSync(root, { recursive: true, force: true }));

function pkg(dir, json, files = {}) {
  mkdirSync(join(root, dir), { recursive: true });
  writeFileSync(join(root, dir, 'package.json'), JSON.stringify(json));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, dir, name), text);
  return join(root, dir);
}

describe('isAllowed', () => {
  it.each([
    ['MIT', true],
    ['(MIT OR GPL-3.0)', true],
    ['(MIT AND Zlib)', false],
    ['Apache 2.0', true],
    ['MIT/X11', true],
    ['ISC (from LICENSE file)', true],
    ['Apache-2.0 (generated by @prisma/client)', true],
    ['LGPL-3.0-or-later', false],
    ['BlueOak-1.0.0', false],
    ['UNKNOWN', false],
  ])('%s', (license, allowed) => {
    expect(isAllowed(license)).toBe(allowed);
  });
});

describe('licenseOf', () => {
  it('reads the field, the old array form and the LICENSE file', () => {
    expect(licenseOf(pkg('a', {}), { license: 'MIT' })).toBe('MIT');
    expect(licenseOf(pkg('b', {}), { licenses: [{ type: 'MIT' }, { type: 'Apache-2.0' }] })).toBe(
      '(MIT OR Apache-2.0)',
    );
    const c = pkg('c', {}, { LICENSE: 'Permission is hereby granted, free of charge, to any person' });
    expect(licenseOf(c, {})).toBe('MIT (from LICENSE file)');
    expect(licenseOf(pkg('d', {}, { 'LICENSE.txt': 'All rights reserved' }), {})).toBe('UNKNOWN (see LICENSE.txt)');
    expect(licenseOf(pkg('e', {}), {})).toBe('UNKNOWN');
    const f = pkg('f', {}, { 'LICENSE.txt': 'Apache License\n  Version 2.0, January 2004' });
    expect(licenseOf(f, { license: 'SEE LICENSE IN LICENSE.txt' })).toBe('Apache-2.0 (from LICENSE file)');
  });
});

describe('walkDependencies', () => {
  it('records the first dependency path and keeps dev dependencies apart', () => {
    pkg('.', { dependencies: { a: '1' }, devDependencies: { d: '1' } });
    pkg('node_modules/a', { name: 'a', version: '1.0.0', license: 'MIT', dependencies: { b: '1' } });
    pkg('node_modules/b', { name: 'b', version: '2.0.0', license: 'GPL-3.0' });
    pkg('node_modules/d', { name: 'd', version: '1.0.0', license: 'MIT' });
    const prod = walkDependencies(root);
    expect(prod.map((e) => [e.name, e.chain.join(' > ')])).toEqual([
      ['a', 'a'],
      ['b', 'a > b'],
    ]);
    expect(walkDependencies(root, { dev: true }).map((e) => e.name)).toContain('d');
  });
});
