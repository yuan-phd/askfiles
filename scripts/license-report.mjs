// Lists the license of every package in the packaged server and collector dependency trees and in
// the shell's own dependencies, and flags licenses outside ALLOWED with the dependency path that pulls
// the package in. Prints Markdown for docs/licenses.md. Reads package.json license fields, falling
// back to the LICENSE file text; no dependency.
// Usage: node scripts/license-report.mjs [resources-dir]
//   resources-dir  holds server/ and collector/; default release/linux-unpacked/resources
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { packageDirs, resolvePackage } from './prune.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const ALLOWED = new Set([
  'MIT',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'Unlicense',
  'Python-2.0',
  'CC0-1.0',
]);

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

/** The license as written in package.json, or guessed from the LICENSE file, or UNKNOWN. */
export function licenseOf(pkgDir, pkg) {
  // node_modules/.prisma holds the client prisma generate writes; it ships under @prisma/client's license.
  if (path.basename(pkgDir) === '.prisma') return 'Apache-2.0 (generated by @prisma/client)';
  const field = pkg.license ?? pkg.licenses;
  const pointer = typeof field === 'string' ? /^SEE LICENSE IN (\S+)/i.exec(field.trim()) : null;
  if (pointer) return licenseFromFile(pkgDir, pointer[1]) ?? field.trim();
  if (typeof field === 'string' && field.trim()) return field.trim();
  if (field && typeof field === 'object' && !Array.isArray(field) && field.type) return String(field.type);
  if (Array.isArray(field) && field.length) {
    const types = field.map((l) => (typeof l === 'string' ? l : l?.type)).filter(Boolean);
    if (types.length) return types.length === 1 ? types[0] : `(${types.join(' OR ')})`;
  }
  const file = fs.readdirSync(pkgDir).find((n) => /^(licen[cs]e|copying)(\.|$)/i.test(n));
  if (file) return licenseFromFile(pkgDir, file) ?? `UNKNOWN (see ${file})`;
  return 'UNKNOWN';
}

function licenseFromFile(pkgDir, file) {
  let text;
  try {
    text = fs.readFileSync(path.join(pkgDir, file), 'utf8');
  } catch {
    return null;
  }
  if (/Permission is hereby granted, free of charge/i.test(text)) return 'MIT (from LICENSE file)';
  if (/Apache License,?\s+Version 2\.0/i.test(text)) return 'Apache-2.0 (from LICENSE file)';
  if (/Permission to use, copy, modify, and\/or distribute/i.test(text)) return 'ISC (from LICENSE file)';
  return null;
}

// Spellings that name an allowed license without its SPDX id.
const ALIASES = { 'Apache 2.0': 'Apache-2.0', 'MIT/X11': 'MIT', CC0: 'CC0-1.0' };

/**
 * Whether an SPDX expression can be used under the allowed licenses: one OR branch whose AND parts
 * are all allowed. Licenses guessed from a LICENSE file count as the license named.
 */
export function isAllowed(license) {
  const expr = license
    .replace(/\s*\((from LICENSE file|generated by [^)]+)\)$/, '')
    .replace(/[()]/g, ' ')
    .trim();
  if (ALIASES[expr]) return true;
  if (/^UNKNOWN/.test(expr)) return false;
  return expr.split(/\s+OR\s+/i).some((branch) =>
    branch
      .split(/\s+AND\s+/i)
      .map((s) => ALIASES[s.trim()] ?? s.trim())
      .every((s) => ALLOWED.has(s)),
  );
}

/**
 * Every package reachable from `rootDir`'s dependencies (and devDependencies when `dev`), with the
 * first dependency path found to it, breadth first.
 */
export function walkDependencies(rootDir, { dev = false } = {}) {
  const rootPkg = readJson(path.join(rootDir, 'package.json')) ?? {};
  const out = new Map();
  const queue = [];
  const seed = { ...rootPkg.dependencies, ...rootPkg.optionalDependencies, ...(dev ? rootPkg.devDependencies : {}) };
  for (const name of Object.keys(seed)) queue.push({ name, from: rootDir, chain: [] });
  while (queue.length) {
    const { name, from, chain } = queue.shift();
    const dir = resolvePackage(name, from, rootDir);
    if (!dir || out.has(dir)) continue;
    const pkg = readJson(path.join(dir, 'package.json')) ?? {};
    const entry = {
      dir,
      name: pkg.name ?? name,
      version: pkg.version ?? '?',
      license: licenseOf(dir, pkg),
      chain: [...chain, name],
    };
    out.set(dir, entry);
    for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies, ...pkg.peerDependencies })) {
      queue.push({ name: dep, from: dir, chain: entry.chain });
    }
  }
  return [...out.values()];
}

function section(title, entries) {
  const rows = new Map();
  for (const e of entries) {
    const key = `${e.name}@${e.version}`;
    if (!rows.has(key)) rows.set(key, e);
  }
  const lines = [
    `## ${title}`,
    '',
    `${rows.size} packages (name and version).`,
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
  ];
  for (const e of [...rows.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  )) {
    lines.push(`| ${e.name} | ${e.version} | ${e.license.replace(/\|/g, '\\|')} |`);
  }
  return lines.join('\n');
}

/** Every installed package of a shipped tree, with its dependency path when one leads to it. */
function shippedTree(treeDir) {
  const reached = new Map(walkDependencies(treeDir).map((e) => [e.dir, e]));
  return packageDirs(path.join(treeDir, 'node_modules')).map((dir) => {
    if (reached.has(dir)) return reached.get(dir);
    const pkg = readJson(path.join(dir, 'package.json')) ?? {};
    const name = pkg.name ?? path.basename(dir);
    return {
      dir,
      name,
      version: pkg.version ?? '?',
      license: licenseOf(dir, pkg),
      chain: ['(installed, no declared path)'],
    };
  });
}

export function report(resourcesDir) {
  const results = [
    { title: 'Packaged server dependencies', entries: shippedTree(path.join(resourcesDir, 'server')) },
    { title: 'Packaged collector dependencies', entries: shippedTree(path.join(resourcesDir, 'collector')) },
    // electron-builder puts the production dependency closure into app.asar, not all of node_modules.
    { title: 'Shell runtime dependencies (app.asar)', entries: walkDependencies(ROOT) },
  ];
  const prodDirs = new Set(results[2].entries.map((e) => e.dir));
  const devEntries = walkDependencies(ROOT, { dev: true }).filter((e) => !prodDirs.has(e.dir));
  results.push({ title: 'Shell development dependencies (not shipped)', entries: devEntries });

  const flagged = [];
  for (const r of results) {
    const seen = new Set();
    for (const e of r.entries) {
      const key = `${e.name}@${e.version}`;
      if (isAllowed(e.license) || seen.has(key)) continue;
      seen.add(key);
      flagged.push({ tree: r.title, ...e });
    }
  }
  const lines = [];
  lines.push('## Licenses outside the allowed list', '');
  lines.push(`Allowed: ${[...ALLOWED].join(', ')}. ${flagged.length} packages, first dependency path found:`, '');
  lines.push('| Tree | Package | License | Pulled in by |', '| --- | --- | --- | --- |');
  for (const f of flagged) {
    lines.push(`| ${f.tree} | ${f.name} ${f.version} | ${f.license} | ${f.chain.join(' > ')} |`);
  }
  lines.push('');
  for (const r of results) lines.push(section(r.title, r.entries), '');
  return { markdown: lines.join('\n'), flagged, counts: results.map((r) => r.entries.length) };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const dir = path.resolve(process.argv[2] ?? path.join(ROOT, 'release/linux-unpacked/resources'));
  if (!fs.existsSync(path.join(dir, 'server/node_modules'))) {
    console.error(`[license-report] no packaged server/node_modules under ${dir}`);
    process.exit(1);
  }
  process.stdout.write(report(dir).markdown);
}
