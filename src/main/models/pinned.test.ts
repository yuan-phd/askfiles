import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { OllamaClient, type FetchLike } from '../ollama/client.js';
import type { ChatModelFile } from '../presets/schema.js';
import { PinnedModelError, verifyPinnedModel } from './pinned.js';

// The 16 GB tier's pinned file, read from the shipped presets so the test follows a re-pin.
const presets = JSON.parse(
  fs.readFileSync(path.join(__dirname, '..', '..', '..', 'config', 'presets.json'), 'utf8'),
) as {
  tiers: { id: string; chatModel: string; chatModelFile?: ChatModelFile }[];
};
const tier16 = presets.tiers.find((t) => t.id === '16gb')!;
const pin = tier16.chatModelFile!;

/** An Ollama whose /api/show answers with this modelfile, as Ollama prints it on each platform. */
function ollamaShowing(modelfile: string): OllamaClient {
  const fetch: FetchLike = async (_url, init) => {
    expect(JSON.parse(String(init?.body))).toEqual({ model: tier16.chatModel });
    return new Response(JSON.stringify({ modelfile }), { status: 200 });
  };
  return new OllamaClient({ baseUrl: 'http://127.0.0.1:1', fetch });
}

const header = '# Modelfile generated by "ollama show"\n# To build a new Modelfile based on this, replace FROM with:\n';

describe('verifyPinnedModel for the 16 GB tier', () => {
  it('accepts the pinned weights under a Windows models folder (backslashes, CRLF)', async () => {
    const from = `FROM C:\\Users\\Ana Lima\\AppData\\Local\\AskFiles\\ollama\\blobs\\sha256-${pin.sha256}`;
    const show = (header + `# FROM ${tier16.chatModel}\n\n${from}\nTEMPLATE "{{ .Prompt }}"\n`).replace(/\n/g, '\r\n');
    const lines: string[] = [];
    await verifyPinnedModel(ollamaShowing(show), tier16.chatModel, pin, (m) => lines.push(m));
    expect(lines).toEqual([
      `[models] ${tier16.chatModel} matches ${pin.repository}@${pin.revision.slice(0, 8)} ${pin.file}`,
    ]);
  });

  it('accepts the pinned weights under a macOS models folder', async () => {
    const from = `FROM /Users/ana/Library/Application Support/AskFiles/ollama/blobs/sha256-${pin.sha256}`;
    await expect(
      verifyPinnedModel(ollamaShowing(header + from + '\n'), tier16.chatModel, pin),
    ).resolves.toBeUndefined();
  });

  it('refuses other weights on Windows and names both digests', async () => {
    const other = 'a'.repeat(64);
    const from = `FROM C:\\Users\\u\\AppData\\Local\\AskFiles\\ollama\\blobs\\sha256-${other}`;
    const err = await verifyPinnedModel(ollamaShowing(header + from + '\r\n'), tier16.chatModel, pin).catch((e) => e);
    expect(err).toBeInstanceOf(PinnedModelError);
    expect((err as Error).message).toContain(`sha256 ${pin.sha256}`);
    expect((err as Error).message).toContain(`Ollama installed sha256 ${other}`);
  });

  it('refuses a modelfile without a blob digest', async () => {
    const err = await verifyPinnedModel(
      ollamaShowing(header + 'FROM C:\\models\\x.gguf\r\n'),
      tier16.chatModel,
      pin,
    ).catch((e) => e);
    expect((err as Error).message).toContain('weights it did not report');
  });
});
